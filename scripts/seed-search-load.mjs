#!/usr/bin/env node
/**
 * Load data for measuring the radius query — slice 3.1c.
 *
 * BRD §14's Phase 3 exit gate asks that search *"meets agreed performance on
 * seeded data"*, and until this existed there was no seeded data: the local
 * database held eight listings, one of them publicly visible. Nothing about the
 * query's behaviour at scale had ever been observed.
 *
 * **Everything it writes is unmistakably fake, and that is not politeness.**
 * `seed-dev.mjs` makes the same argument and this one carries it further,
 * because this writes tens of thousands of rows rather than one category:
 *
 *   - it refuses any database that is not `rental_dev` or `rental_test`;
 *   - every row it creates is tagged `LOADTEST` in a column somebody will see;
 *   - it writes **no audit entry**, which is the honest record that nobody did
 *     this — a seeded row with a fabricated actor is worse than one with no
 *     trail at all;
 *   - `--clean` removes exactly what it made and nothing else.
 *
 * **The encrypted column holds a marker, not an envelope.** `encryptedDetail`
 * is `NOT NULL` and real rows hold an AES envelope this script has no key for.
 * It writes a plain marker instead, which means **the owner-facing pages cannot
 * read these listings** — decryption will throw. That is fine and deliberate:
 * this data exists to be *searched*, and search never joins that column. It is
 * also the reason the guard above matters.
 *
 * **Rows are generated by Postgres, not by Node.** One `INSERT … SELECT` over
 * `generate_series` per table, so fifty thousand listings take seconds rather
 * than fifty thousand round trips. The coordinates come from PostGIS's own
 * `ST_Project`, which is the destination-point formula the application's
 * `applyFuzzOffset` implements — on the spheroid here and on a sphere there, a
 * difference of a few metres inside a deliberate 500–1000 m blur.
 *
 * Usage:
 *   node scripts/seed-search-load.mjs --count 50000
 *   node scripts/seed-search-load.mjs --clean
 */

import { execFileSync } from 'node:child_process';
import { parseArguments } from './lib/search-load-options.mjs';

const PG_CONTAINER = 'rental-postgres';
const PG_USER = process.env.POSTGRES_USER ?? 'rental';

/** Stamped on every row, so a human can see what this is at a glance. */
const TAG = 'LOADTEST';
const CATEGORY_SLUG = 'loadtest-example-category';

/**
 * Where the listings go.
 *
 * **Clustered on real cities rather than scattered over a bounding box**, and
 * that is the difference between measuring the index and measuring nothing. A
 * uniform spread across the UK's rectangle puts most listings in the sea and
 * gives every radius query a nearly empty answer — which would make any index
 * look fast. Real supply clusters, so the query has to be measured against
 * clusters.
 */
