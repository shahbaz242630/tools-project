/**
 * The §3.4.3 worked example, as a document — slice 5.3a.
 *
 * **The arithmetic is not here.** It is in `apps/api/src/pricing/unit-economics.ts`,
 * where coverage counts it and where slice 5.3b's category gate can call it at
 * runtime. This file turns the result into prose and decides whether the run
 * failed, which is the same division `measure-search.mjs` makes: the query lives
 * in the adapter and only the reporting lives here.
 *
 * In `lib/` for the reason `search-load-options.mjs` gives — the executable
 * carries a shebang and Vite cannot parse one, so anything with a test lives here.
 */

/**
 * The activity levels the report walks.
 *
 * **A curve rather than a point, because nobody has measured the point.** Stripe
 * charges £2 per active connected account per month, so what a booking costs
 * depends on how often its owner lets — and this platform has never traded. The
 * report shows the shape and names the crossing rather than asserting a number
 * somebody would have had to invent.
 */
export const ACTIVITY_LEVELS = Object.freeze([1, 2, 4, 8]);

/**
 * Whether §3.4.3's binding clause is satisfied for a category.
 *
 * §3.4.3: *"A category may not be enabled for public booking if contribution
 * margin at the minimum booking total is negative."* **That is the only clause in
 * §3.4.3 that forbids anything** — the three-point table beside it is a
 * documentation requirement — so it is the one the exit code is wired to.
 *
 * **Judged at one booking per owner per month**, deliberately the most pessimistic
 * activity level, because it is the one a new marketplace actually has: an owner
 * who has just listed their first item has completed one booking that month by
 * definition. Judging at a busier level would pass the gate by assuming the
 * traction the gate exists to survive the absence of.
 */
export function meetsMinimumMarginRule(category) {
  const atFloor = category.rows.find(
    (row) => row.isMinimumBookingTotal && row.bookingsPerMonth === 1,
  );

  if (atFloor === undefined) {
    return {
      passed: false,
      reason:
        'no row was computed at the minimum booking total, so the rule could not be checked',
    };
  }

  if (atFloor.contributionMarginMinor < 0) {
    return {
      passed: false,
      reason:
        `contribution margin at the minimum booking total (${formatMinor(atFloor.grossMinor)}) ` +
        `is ${formatMinor(atFloor.contributionMarginMinor)} for an owner letting once a month` +
        (category.breakEvenBookingsPerMonth === null
          ? ', and no level of owner activity would make it positive'
          : `, and it needs ${String(category.breakEvenBookingsPerMonth)} bookings a month to turn positive`),
    };
  }

  return { passed: true, reason: null };
}

/**
 * Basis points as a percentage, without ever touching a float.
 *
 * **Dividing by a hundred and formatting to two decimal places is the obvious
 * version, and the invariant checker is right to refuse it.** This is not money, so nothing would have been lost here —
 * but the rule exists because that formatting habit is how a float creeps into a total, and a
 * file about money is the worst place to teach the eye that it is fine. Integer
 * division and a remainder are exact and no longer.
 */
export function formatBasisPoints(basisPoints) {
  const whole = Math.floor(basisPoints / 100);
  const hundredths = basisPoints % 100;

  return `${String(whole)}.${String(hundredths).padStart(2, '0')}%`;
}

/** Pence to a readable £, including negatives. */
export function formatMinor(minor) {
  const sign = minor < 0 ? '-' : '';
  const absolute = Math.abs(minor);

  return `${sign}£${String(Math.floor(absolute / 100))}.${String(absolute % 100).padStart(2, '0')}`;
}

/**
 * The whole document.
 *
 * **Markdown, written to `docs/`, because §3.4.3 asks for something *documented*
 * and `docs/` is gitignored** — the BRD carries unit economics and strategy, and
 * this file now carries the same. It is generated rather than hand-written so it
 * cannot drift from the model that produces it.
 */
export function renderReport({ categories, assumptions, generatedOn, costModel }) {
  const lines = [];

  lines.push('# Unit economics — the §3.4.3 worked example');
  lines.push('');
  lines.push(
    '**Generated by `node scripts/unit-economics.mjs`. Do not edit by hand** — it is',
    'regenerated from the real category configuration and the cost model in',
    '`apps/api/src/pricing/cost-model.ts`, so an edit here is a number that disagrees',
    'with the code.',
  );
  lines.push('');
  lines.push(
    `Generated: **${generatedOn}**. Gitignored, like everything in \`docs/\`.`,
  );
  lines.push('');
  lines.push(
    'BRD §3.4.3 requires, before Phase 5 exits, a documented worked example per',
    'category showing gross booking value, renter fee, owner commission, every cost',
    'component in §3.4.1, and the resulting contribution margin — at the minimum',
    'booking total, at the median expected booking, and at the highest deposit band.',
  );
  lines.push('');
  lines.push(
    '**The highest-deposit-band column is missing and that is not an oversight.**',
    'Deposit bands do not exist yet: `category_versions.riskLevel` carries a comment',
    'saying it *later* drives them, and damage security is unbuilt. That row arrives',
    'with §8.7.2. **The binding clause is unaffected** — §3.4.3 forbids public',
    'booking only on negative margin *at the minimum booking total*, which is',
    'computed in full below.',
  );
  lines.push('');

  for (const category of categories) {
    lines.push(`## \`${category.slug}\` — version ${String(category.versionNumber)}`);
    lines.push('');
    lines.push(
      `Owner commission **${formatBasisPoints(category.ownerCommissionBasisPoints)}** · ` +
        `renter fee **${formatBasisPoints(category.renterFeeBasisPoints)}** · ` +
        `minimum booking total **${formatMinor(category.minimumBookingTotalMinor)}** · ` +
        `minimum platform fee **${formatMinor(category.minimumPlatformFeeMinor)}**`,
    );
    lines.push('');

    const verdict = meetsMinimumMarginRule(category);
    lines.push(
      verdict.passed
        ? '**§3.4.3: PASSES.** Contribution margin at the minimum booking total is positive.'
        : `**§3.4.3: FAILS — this category may not be enabled for public booking.** ${verdict.reason}.`,
    );
    lines.push('');

    lines.push(
      '| Booking | Owner lets | Renter pays | Renter fee | Owner commission | Owner gets | Platform revenue | Total cost | **Margin** |',
    );
    lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');

    for (const row of category.rows) {
      lines.push(
        `| ${formatMinor(row.grossMinor)}${row.isMinimumBookingTotal ? ' *(floor)*' : ''}${row.isMedian ? ' *(median)*' : ''} ` +
          `| ${String(row.bookingsPerMonth)}/mo ` +
          `| ${formatMinor(row.renterPaysMinor)} ` +
          `| ${formatMinor(row.renterFeeMinor)} ` +
          `| ${formatMinor(row.ownerCommissionMinor)} ` +
          `| ${formatMinor(row.ownerProceedsMinor)} ` +
          `| ${formatMinor(row.platformRevenueMinor)} ` +
          `| ${formatMinor(row.totalCostMinor)} ` +
          `| **${formatMinor(row.contributionMarginMinor)}** |`,
      );
    }
    lines.push('');

    lines.push(
      category.breakEvenBookingsPerMonth === null
        ? '**Break-even at the floor: never.** No amount of owner activity makes a booking at this value pay for itself — the fixed costs alone exceed the platform revenue.'
        : `**Break-even at the floor: ${String(category.breakEvenBookingsPerMonth)} booking(s) per owner per month.**`,
    );
    lines.push('');

    lines.push('### Where the money goes, at the minimum booking total');
    lines.push('');
    lines.push('| §3.4.1 component | Cost |');
    lines.push('| --- | --- |');
    for (const [component, minor] of Object.entries(category.floorCostBreakdown)) {
      lines.push(`| ${component} | ${formatMinor(minor)} |`);
    }
    lines.push('');
  }

  lines.push('## The cost model');
  lines.push('');
  lines.push('| Component | Value | Source |');
  lines.push('| --- | --- | --- |');
  for (const entry of costModel) {
    lines.push(`| ${entry.field} | ${entry.value} | ${entry.source} |`);
  }
  lines.push('');

  lines.push('## Assumptions — the product owner’s to confirm');
  lines.push('');
  lines.push(
    'Every number below is a guess rather than a published rate. They are listed so',
    'the document does not overstate its own authority: a model whose assumptions are',
    'invisible reads as a measurement.',
  );
  lines.push('');
  for (const assumption of assumptions) {
    lines.push(`- **\`${assumption.field}\`** — ${assumption.basis}`);
  }
  lines.push('');

  return lines.join('\n');
}
